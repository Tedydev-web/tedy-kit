export const labels = (lang) => ({ ...LABELS.en, ...(LABELS[lang] ?? {}) });

export const fill = (text, values) => text.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));

export const chatLanguage = () => loadConfig().language.chat;

function main([asked]) {
  const lang = asked ?? chatLanguage();
  const pack = labels(lang);
  const rows = Object.entries(pack).filter(([key]) => !key.startsWith("doc."));
  process.stdout.write(`language: ${LABELS[lang] ? lang : `${lang} (no pack; English shown)`}\n\n| Key | Label |\n|---|---|\n${rows.map(([key, text]) => `| \`${key}\` | ${text} |`).join("\n")}\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main(process.argv.slice(2)));
