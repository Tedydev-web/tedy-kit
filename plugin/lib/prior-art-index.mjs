import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

export const DOMAINS = {
  "agent-skills": "writing skills, agents, plugins and their instructions",
  "ai-models": "model generations, their traits, and choosing or switching models",
  backend: "services, APIs, data stores and server-side code",
  blockchain: "wallets, exchanges, chains and smart contracts",
  cost: "tokens, prompt cache and quota",
  evals: "measuring agent behaviour with scenarios, baselines, arms and judges",
  frontend: "web and mobile UI, design systems and client code",
  governance: "standards, rule ledgers, decision records and drift",
  guardrails: "gates and hooks that stop unsafe agent actions",
  infra: "servers, CI/CD, containers, networking and high availability",
  platform: "Claude Code and other hosts: their surfaces and compatibility",
  "product-pm": "requirements, trackers, reviews of specs and design",
  qa: "testers, end users and acceptance of what is built",
  release: "versioning, changelogs, distribution and published docs",
  research: "finding, screening, ranking and distilling sources",
  security: "secrets, permissions, supply chain and attack surface",
  testing: "test-first work, verification and tests that can fail",
};
export const CHANNELS = ["github", "docs", "blog", "reddit", "x", "youtube", "facebook", "substack", "npm", "hacker-news", "paper", "report"];

const CARD = /^---\n(?:(?!---\n)[^\n]*\n)*?name: /;
const DATE = /^\d{4}-\d{2}-\d{2}$/;

const split = (text) => {
  const [, front = "", body = ""] = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/) ?? [];
  const field = (key) => front.match(new RegExp(`^${key}: (.*)$`, "m"))?.[1]?.trim();
  const list = (key) => (field(key) ?? "").split(",").map((item) => item.trim()).filter(Boolean);
  return { body, field, list };
};

export function parseCard({ slug, text }) {
  const { body, field, list } = split(text);
  const lessonsBlock = body.split(/^## Lessons\n/m)[1]?.split(/^## /m)[0] ?? "";
  const lessons = lessonsBlock.split("\n").filter((line) => line.startsWith("- ") && !/^- Not covered\b/.test(line))
    .map((line) => line.slice(2).split(/: |[.;] [Tt]ouches /)[0].replace(/[;,]\s*but\b.*$/, "").trim());
  return { kind: "card", slug, name: field("name"), domains: list("domains"), useWhen: field("use-when") ?? "", lessons };
}

export function parseNote({ slug, text, place }) {
  const { body, field, list } = split(text);
  const sourcesBlock = body.split(/^## Sources\n/m)[1]?.split(/^## /m)[0] ?? "";
  const sources = sourcesBlock.split("\n").filter((line) => /^- (https?:\/\/|plans\/)/.test(line)).map((line) => line.slice(2).trim());
  return { kind: "note", slug, place, name: field("title"), domains: list("domains"), useWhen: field("use-when") ?? "", channels: list("channels"), verified: field("verified"), read: field("read"), sources, lessons: [] };
}

export function entryErrors(entries) {
  return entries.flatMap((entry) => {
    const id = entry.kind === "note" ? `notes/${entry.slug}` : entry.slug;
    const errors = [];
    if (!entry.domains.length) errors.push(`${id}: no domains: line; pick from ${Object.keys(DOMAINS).join(", ")}`);
    errors.push(...entry.domains.filter((domain) => !(domain in DOMAINS)).map((domain) => `${id}: domain ${domain} is not in the vocabulary`));
    if (!entry.useWhen) errors.push(`${id}: no use-when: line`);
    if (entry.kind !== "note") return errors;
    if (!entry.name) errors.push(`${id}: no title: line`);
    if (!entry.channels.length) errors.push(`${id}: no channels: line`);
    errors.push(...entry.channels.filter((channel) => !CHANNELS.includes(channel)).map((channel) => `${id}: channel ${channel} is not one of ${CHANNELS.join(", ")}`));
    if (!["yes", "no"].includes(entry.verified)) errors.push(`${id}: verified must be yes or no`);
    if (!DATE.test(entry.read ?? "")) errors.push(`${id}: read must be the YYYY-MM-DD the sources were read`);
    if (!entry.sources.length) errors.push(`${id}: no source URL under ## Sources`);
    if (entry.place === "public" && !entry.sources.some((source) => source.startsWith("http"))) errors.push(`${id}: a public note needs a public source URL`);
    return errors;
  });
}

const HEAD = "Every studied source and distilled finding, grouped by what it teaches. Read the domain before you design something in it, then open the entries. A card is one GitHub source read at file:line with pinned evidence; a note is one finding distilled from posts, videos, docs or reports, with its sources and whether they were re-read. Generated by `node plugin/scripts/prior-art-index.mjs write`; `npm test` fails when this file and the entries disagree.";

export function renderIndex(entries, { link = (entry) => (entry.kind === "note" ? `notes/${entry.slug}.md` : `${entry.slug}.md`), title = "Prior-art knowledge index" } = {}) {
  const groups = Object.entries(DOMAINS).map(([domain, about]) => [domain, about, entries.filter((entry) => entry.domains.includes(domain)).sort((a, b) => a.name.localeCompare(b.name))]).filter(([, , members]) => members.length);
  const lines = [`# ${title}`, "", HEAD, "", "## Contents", "", ...groups.map(([domain, , members]) => `- ${domain}: ${members.length} ${members.length === 1 ? "entry" : "entries"}`)];
  for (const [domain, about, members] of groups) {
    lines.push("", `## ${domain}: ${about}`, "");
    for (const entry of members) {
      const tag = entry.kind === "note" ? ` (note, ${entry.channels.join(", ")}, ${entry.verified === "yes" ? "verified" : "unverified"} ${entry.read})` : "";
      lines.push(`- [${entry.name}](${link(entry)})${tag}: ${entry.useWhen}`);
      for (const lesson of entry.lessons) lines.push(`  - ${lesson}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

export function kitEntries(repo, { withPrivate = false } = {}) {
  const tracked = execFileSync("git", ["-C", repo, "ls-files", "docs/prior-art"], { encoding: "utf8" }).split("\n");
  const cards = tracked.filter((file) => /^docs\/prior-art\/[^/]+\.md$/.test(file))
    .map((file) => ({ file, text: readFileSync(join(repo, file), "utf8") }))
    .filter(({ text }) => CARD.test(text))
    .map(({ file, text }) => parseCard({ slug: file.slice("docs/prior-art/".length, -3), text }));
  const notes = tracked.filter((file) => /^docs\/prior-art\/notes\/[^/]+\.md$/.test(file))
    .map((file) => parseNote({ slug: file.slice("docs/prior-art/notes/".length, -3), text: readFileSync(join(repo, file), "utf8"), place: "public" }));
  const privateDir = join(repo, "docs/prior-art/private/notes");
  const privateNotes = withPrivate && existsSync(privateDir)
    ? readdirSync(privateDir).filter((file) => file.endsWith(".md")).map((file) => parseNote({ slug: file.slice(0, -3), text: readFileSync(join(privateDir, file), "utf8"), place: "private" }))
    : [];
  return [...cards, ...notes, ...privateNotes];
}

export function privateLink(entry) {
  if (entry.kind === "card") return `../${entry.slug}.md`;
  return entry.place === "private" ? `notes/${entry.slug}.md` : `../notes/${entry.slug}.md`;
}

export function run(argv = process.argv.slice(2), repo = fileURLToPath(new URL("../../", import.meta.url))) {
  const [command] = argv;
  if (!["check", "write"].includes(command)) {
    console.error("usage: prior-art-index.mjs check | write");
    process.exit(2);
  }
  const publicEntries = kitEntries(repo);
  const allEntries = kitEntries(repo, { withPrivate: true });
  const errors = entryErrors(allEntries);
  for (const error of errors) console.error(error);
  if (errors.length) process.exit(1);
  const targets = [[join(repo, "docs/prior-art/index.md"), renderIndex(publicEntries)]];
  if (existsSync(join(repo, "docs/prior-art/private"))) targets.push([join(repo, "docs/prior-art/private/index.md"), renderIndex(allEntries, { link: privateLink, title: "Prior-art knowledge index (private, this machine only)" })]);
  let stale = 0;
  for (const [file, text] of targets) {
    if ((existsSync(file) ? readFileSync(file, "utf8") : "") === text) continue;
    if (command === "write") writeFileSync(file, text);
    else stale += 1;
    console.log(`${command === "write" ? "wrote" : "stale"}: ${file.slice(repo.length)}`);
  }
  console.log(`${publicEntries.length} public entries, ${allEntries.length - publicEntries.length} private notes`);
  if (stale) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) run();
